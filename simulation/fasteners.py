def screws_of(group):
    """The derived fasteners of one link, in the order the table lists."""
    return STACKS[group]


def nuts_of(group):
    """The derived fasteners of one link that carry a nut."""
    return tuple(f for f in STACKS[group] if f.nut_span is not None)


def declare_screws(group):
    """One screw node per derived stack, for a class body to hold."""
    return [screw(fastener) for fastener in screws_of(group)]


def declare_nuts(group):
    """One nut node per derived stack that carries one."""
    return [nut(fastener) for fastener in nuts_of(group)]


def place_all(node, group):
    """Stand every screw and nut of a link where its stack puts it."""
    for child, fastener in zip(node.screws, screws_of(group)):
        place_screw(child, fastener)
    for child, fastener in zip(node.nuts, nuts_of(group)):
        place_nut(child, fastener)
