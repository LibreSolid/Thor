"""The bolts and nuts, derived from the parts' own holes.

Thor's design models no fastener at all: every screw and nut in the machine
is implied by holes and pockets and stated nowhere in the repository. This
table is what the printed parts' own geometry says, read by
`simulation.tools.geometry.fastener_stacks` and written by
``python -m simulation.tools.emit_fasteners``:

- **Ø3.4 clearance holes** — the M3 shank size, cut 400 times across the
  machine — and four **Ø4.2** holes in the belt tensioners, for M4.
- **Ø5.9 counterbores** — where a socket head bears.
- **5.80 across flats**, six planes 2.90 from the axis — an M3 nut with
  0.3 mm of print clearance.

Coaxial holes are clustered onto shared axes and each axis is split into
contiguous stacks: a screw fastens parts of one rigid link, so the
derivation runs one sub-assembly at a time in that link's own frame, and a
cluster can never reach across a joint and invent a screw through it. Each
stack gets the shortest standard M3 length that spans it, plus the nut the
design cut a pocket for.

Seventy-one further stacks are a hole through one part with neither a
counterbore nor a pocket: nothing in the geometry says whether they take a
screw, so the model fits none and `docs/measurements.md` lists them.

`simulation/test_fasteners.py` re-runs the probe and compares this table
entry for entry.
"""

from collections import namedtuple

import cadquery as cq

from solid_node.node import CadQueryNode
from solid_node.parameters import Length

from simulation import materials, placing

#: One derived fastener: its size, the standard length chosen, the axis and
#: origin of its stack in the link's own frame, the two ends of the stack
#: along that axis, which end the head bears on, and the pocket its nut
#: sits in, if the design cut one.
Fastener = namedtuple(
    'Fastener', 'kind length axis origin low high head_end nut_span')

#: An M3 socket head is 5.50 across and 3.00 tall; an M4's is 7.00 by 4.00.
HEAD_DIAMETER = {'M3': 5.50, 'M4': 7.00}
HEAD_HEIGHT = {'M3': 3.00, 'M4': 4.00}
#: Nominal thread diameters and nut sizes.
SHANK_DIAMETER = {'M3': 2.98, 'M4': 3.98}
NUT_ACROSS_FLATS = {'M3': 5.50, 'M4': 7.00}
NUT_THICKNESS = {'M3': 2.40, 'M4': 3.20}

# A screw head bears on its face and a nut on its pocket floor: they are
# seated exactly, not held off it. The exact kernel answers a tangency as
# contact rather than interference, so there is nothing here for a gap to
# resolve — and Thor has stacks with exactly 3.00 mm of head space for a
# 3.00 mm head, where a gap would be an interference the design does not
# have.


class SocketHeadScrew(CadQueryNode):
    """A socket-head cap screw, its head's bearing face at the origin.

    The head sits below z=0 and the shank runs up +Z, so standing one on a
    stack is a matter of pointing +Z along the hole and putting the origin
    on the face the head bears against. The thread is drawn as a plain
    shank: nothing in Thor hangs on a thread form, and a real one would
    cost more triangles than the whole rest of the machine.
    """

    color = materials.STEEL

    shank_diameter = Length(2.98, min=0)
    length = Length(min=0)
    head_diameter = Length(5.5, min=0)
    head_height = Length(3.0, min=0)
    socket_across_flats = Length(2.5, min=0)

    def render(self):
        head = (cq.Workplane('XY').circle(self.head_diameter / 2)
                .extrude(self.head_height)
                .translate((0, 0, -self.head_height)))
        socket = (cq.Workplane('XY')
                  .polygon(6, self.socket_across_flats /
                           0.8660254037844386)
                  .extrude(self.head_height * 0.7)
                  .translate((0, 0, -self.head_height)))
        shank = (cq.Workplane('XY').circle(self.shank_diameter / 2)
                 .extrude(self.length))
        return head.cut(socket).union(shank)


class HexNut(CadQueryNode):
    """A hex nut, centred on the origin, its axis along Z."""

    color = materials.STEEL

    across_flats = Length(5.5, min=0)
    thickness = Length(2.4, min=0)
    bore = Length(3.0, min=0)

    def render(self):
        body = (cq.Workplane('XY')
                .polygon(6, self.across_flats / 0.8660254037844386)
                .extrude(self.thickness)
                .translate((0, 0, -self.thickness / 2)))
        bore = (cq.Workplane('XY').circle(self.bore / 2)
                .extrude(self.thickness + 2)
                .translate((0, 0, -self.thickness / 2 - 1)))
        return body.cut(bore)


def screw(fastener):
    """The screw one derived stack takes."""
    return SocketHeadScrew(
        shank_diameter=SHANK_DIAMETER[fastener.kind],
        length=float(fastener.length),
        head_diameter=HEAD_DIAMETER[fastener.kind],
        head_height=HEAD_HEIGHT[fastener.kind],
        socket_across_flats=2.5 if fastener.kind == 'M3' else 3.0)


def nut(fastener):
    """The nut one derived stack takes, where the design cut a pocket."""
    return HexNut(across_flats=NUT_ACROSS_FLATS[fastener.kind],
                  thickness=NUT_THICKNESS[fastener.kind],
                  bore=SHANK_DIAMETER[fastener.kind] + 0.02)


def place_screw(child, fastener):
    """Stand a screw on its stack, head on the end the design counterbored."""
    axis = fastener.axis
    if fastener.head_end == 'low':
        direction = axis
        along = fastener.low
    else:
        direction = tuple(-v for v in axis)
        along = -fastener.high
    point = tuple(o + along * d for o, d in zip(fastener.origin, direction))
    placing.align_z(child, direction, point)


def place_nut(child, fastener):
    """Seat a nut in the middle of the pocket the design cut for it."""
    low, high = fastener.nut_span
    middle = (low + high) / 2.0
    point = tuple(o + middle * a for o, a in zip(fastener.origin,
                                                 fastener.axis))
    placing.align_z(child, fastener.axis, point)

