def links(group):
    """The placed instances of one sub-assembly, or of the root."""
    return LINKS[group]


def link(group, label):
    """One placed instance by the label the design gives it."""
    for placed in LINKS[group]:
        if placed.label == label:
            return placed
    raise KeyError('%s has no instance labelled %r' % (group, label))


def printed(group):
    """The instances of `group` that come from a published printed part."""
    return tuple(p for p in LINKS[group] if p.source is not None)


def bought(group):
    """The instances of `group` the design places but does not publish."""
    return tuple(p for p in LINKS[group] if p.source is None)


def components(group, *names):
    """The bought instances of `group` of the named component kinds."""
    wanted = frozenset(names)
    return tuple(p for p in LINKS[group] if p.component in wanted)


def part_name(placed):
    """The printed part a placed instance is an instance of."""
    if placed.source is None:
        raise ValueError('%r is a bought component, not a printed part'
                         % (placed.label,))
    return placed.source.split('.')[0]
