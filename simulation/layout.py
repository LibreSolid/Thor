"""Where every part of Thor sits, in the design's own frame.

This module defines no node. It holds the numbers the machine is built
from, and it is imported directly (never through the package) by every
sub-assembly, so the framework's import walk invalidates exactly the nodes
that read an edited number.

The machine frame is the FreeCAD assembly's own: **Z up, origin on the
mounting face of BaseBot**, X toward the electronics box's open side, Y
completing the right-handed set. At the home pose the arm stands fully
extended along +Z with the tool pointing up.

`LINKS` is transcribed from the design's own FreeCAD Assembly4 documents,
which store each link's solved global placement. It is generated by
``python -m simulation.tools.emit_layout`` and checked, entry for entry,
against a fresh read of those documents by ``simulation/test_layout.py``.
Every translation is in millimetres, every angle in degrees, and every
rotation is stated as one axis and one angle applied before the
translation — the order ``node.rotate(angle, axis)`` then
``node.translate(t)`` reproduces.
"""

from collections import namedtuple

