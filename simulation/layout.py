# --- the gear pairs -------------------------------------------------------
#
# The design's assembly leaves every printed gear pair interpenetrating: it
# never put a pinion on its shaft at an angle that meshes. A builder does,
# so the model does too, and each phase below is measured rather than
# chosen: the pinion is swept through one tooth pitch against its mate by
# `simulation.tools.geometry.mesh_window`, and it is put on at the centre of
# the window where the pair shares least.
#
# Two of the five pairs never reach zero however they are phased, because
# something other than a tooth fouls: those floors are recorded here and
# again in `simulation.seats`, and they are findings about the design, not
# tolerances the model grants itself.

